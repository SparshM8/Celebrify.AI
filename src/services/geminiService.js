/**
 * 3. DYNAMIC CASCADING TASK DELAY ENGINE
 * Recalculates milestone sequencing when an upstream task is delayed
 */
export function calculateCascadingTaskDelays(tasks, delayedTaskId, delayDays) {
  const updatedTasks = JSON.parse(JSON.stringify(tasks));
  const delayedIndex = updatedTasks.findIndex(t => t.id === delayedTaskId);
  
  if (delayedIndex === -1) return updatedTasks;

  const targetTask = updatedTasks[delayedIndex];
  targetTask.isDelayed = true;
  targetTask.delayDays = (targetTask.delayDays || 0) + delayDays;

  // Track visited tasks to prevent circular cascades
  const visited = new Set([delayedTaskId]);
  const queue = [delayedTaskId];

  while (queue.length > 0) {
    const currentId = queue.shift();
    // Find all tasks that depend directly or indirectly on currentId
    updatedTasks.forEach(task => {
      if (task.dependencies && task.dependencies.includes(currentId) && !visited.has(task.id)) {
        task.cascadedDelayDays = (task.cascadedDelayDays || 0) + delayDays;
        task.isCriticalRisk = true;
        visited.add(task.id);
        queue.push(task.id);
      }
    });
  }

  return updatedTasks;
}

