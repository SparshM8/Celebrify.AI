const GEMINI_API_ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent";

/**
 * Retrieves the user-provided Gemini API key securely from sessionStorage or environment variables
 */
export const getApiKey = () => {
  return (
    sessionStorage.getItem("CELEBRIFY_GEMINI_API_KEY") ||
    import.meta.env.VITE_GEMINI_API_KEY ||
    import.meta.env.GEMINI_API_KEY ||
    ""
  );
};

export const setApiKey = (key) => {
  if (key) {
    sessionStorage.setItem("CELEBRIFY_GEMINI_API_KEY", key.trim());
  } else {
    sessionStorage.removeItem("CELEBRIFY_GEMINI_API_KEY");
  }
};

/**
 * Sends a prompt to Google Gemini 3.8 Flash API with retry on temporary high demand
 */
async function callGeminiApi(promptText, apiKey, retries = 1) {
  if (!apiKey) throw new Error("No API key provided");

  try {
    const response = await fetch(`${GEMINI_API_ENDPOINT}?key=${apiKey}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [
          {
            parts: [{ text: promptText }]
          }
        ],
        generationConfig: {
          temperature: 0.7,
          maxOutputTokens: 2048,
          responseMimeType: "application/json"
        }
      })
    });

    if (response.status === 503 && retries > 0) {
      // 503 spike in demand on Gemini 3.8 Flash, pause and retry once
      await new Promise(res => setTimeout(res, 1200));
      return await callGeminiApi(promptText, apiKey, retries - 1);
    }

    if (!response.ok) {
      const errorData = await response.json().catch(() => ({}));
      throw new Error(errorData.error?.message || `API error: ${response.statusText}`);
    }

    const data = await response.json();
    const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!rawText) throw new Error("No content generated by Gemini 3.8 Flash");

    return JSON.parse(rawText);
  } catch (err) {
    throw err;
  }
}

