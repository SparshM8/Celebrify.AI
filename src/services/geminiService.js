/**
 * 5. BONUS FEATURE: "WHAT-IF" SCENARIO RIPPLE SIMULATOR
 * Calculates holistic ripple effect of modifying core variables
 */
export function simulateScenarioRipple({ baseEvent, deltaGuests, venueTypeShift, tierMultiplier }) {
  const originalGuests = baseEvent.guestCount || 100;
  const newGuests = Math.max(10, originalGuests + deltaGuests);
  const guestRatio = newGuests / originalGuests;
  
  const baseBudget = baseEvent.budget || 10000;
  
  // Cost sensitivity factors
  const cateringPerHead = (baseBudget * 0.30) / originalGuests;
  const rentalsPerTable = 120; // 1 table per 8-10 guests
  const originalTables = Math.ceil(originalGuests / 8);
  const newTables = Math.ceil(newGuests / 8);
  const tableDiff = newTables - originalTables;

  // New calculated components
  const newCateringSpend = Math.round(newGuests * cateringPerHead * tierMultiplier);
  const cateringDelta = newCateringSpend - Math.round(originalGuests * cateringPerHead);

  const rentalDelta = tableDiff * rentalsPerTable;
  const stationeryDelta = Math.round((newGuests - originalGuests) * 8);

  const totalBudgetDelta = cateringDelta + rentalDelta + stationeryDelta;
  const projectedTotalBudget = Math.round(baseBudget + totalBudgetDelta);

  // Venue Capacity Risk
  let venueCapacityRisk = "Safe";
  let venueWarning = "Venue capacity comfortably accommodates all guests.";
  if (venueTypeShift === "Intimate Boutique" && newGuests > 75) {
    venueCapacityRisk = "High Risk";
    venueWarning = `Capacity warning: An intimate boutique space typically caps at 75 guests (${newGuests} requested). Stagger arrival or secure outdoor overflow.`;
  } else if (newGuests > originalGuests * 1.4) {
    venueCapacityRisk = "Moderate Risk";
    venueWarning = `Guest expansion (+${deltaGuests}) may require additional fire safety permits, extra servers (1 per 15 guests), and 2 additional bar stations.`;
  }

  // Timeline Urgency
  let timelineUrgency = "Normal";
  let timelineAdvice = "Standard planning schedule is maintained.";
  if (deltaGuests > 50) {
    timelineUrgency = "High Urgency";
    timelineAdvice = "Advance final catering headcount deadline by 10 business days. Rentals must be confirmed immediately due to linen/chair inventory limits.";
  }

  return {
    originalGuests,
    newGuests,
    projectedTotalBudget,
    totalBudgetDelta,
    breakdownChanges: {
      catering: { current: Math.round(originalGuests * cateringPerHead), projected: newCateringSpend, delta: cateringDelta },
      rentals: { current: originalTables * rentalsPerTable, projected: newTables * rentalsPerTable, delta: rentalDelta },
      stationery: { delta: stationeryDelta }
    },
    tablesNeeded: newTables,
    staffingRatioNeeded: Math.ceil(newGuests / 15),
    venueCapacityRisk,
    venueWarning,
    timelineUrgency,
    timelineAdvice
  };
}

